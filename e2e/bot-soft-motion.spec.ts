import { test, expect } from './helpers/bot-pair';

test('soft face lives at idle, works continuously and respects motion preferences [AC:bot-soft-motion#AC-1] [AC:bot-soft-motion#AC-2] [AC:bot-soft-motion#AC-3]', async ({ page, botPair }) => {
  const bots = botPair.map((bot, i) => i ? bot : { ...bot, faceStyle: 'soft', faceShape: 'pebble', faceColor: 'coral', faceExpression: 'happy', avatar: null });
  const [a, b] = bots;
  let active = 0;
  await page.route('**/api/bots', r => r.fulfill({ json: { bots } }));
  await page.route('**/api/bot-work/status', r => r.fulfill({ json: { bots: bots.map(bot => ({ bot, activeWorkCount: bot.id === a.id ? active : 0 })) } }));
  const room = { id: 'soft-motion', title: 'Soft motion', botIds: [a.id, b.id], hostBotId: a.id, status: 'active', maxBotTurns: 2 };
  await page.route('**/api/bot-rooms', r => r.fulfill({ json: { rooms: [room] } }));
  await page.route('**/api/bot-rooms/soft-motion', r => r.fulfill({ json: { room } }));
  await page.route('**/api/bot-rooms/soft-motion/messages*', r => r.fulfill({ json: { messages: [], hasMore: false } }));
  await page.route('**/api/bot-rooms/soft-motion/turns', r => r.fulfill({ json: { turns: [] } }));
  await page.goto('/#/bot');
  const row = page.locator('#sessionListMini .list-item--bot-chat').filter({ has: page.locator('.session-item__title').getByText(a.name, { exact: true }) });
  const face = row.locator('[data-soft-bot-face]');
  await expect(face).toHaveAttribute('data-face-working', 'false');
  await row.scrollIntoViewIfNeeded();
  await expect(face.locator('[data-bob]')).toHaveCSS('animation-name', 'bot-face-idle-body');
  await expect(face.locator('[data-eye]')).toHaveCSS('animation-name', 'bot-face-idle-blink');
  await expect(face).toHaveAttribute('data-soft-bot-color', 'coral');
  await row.click(); active = 1;
  await expect(face).toHaveAttribute('data-face-working', 'true');
  await expect(page.locator('.chat-panel-header--bot [data-soft-bot-face]')).toHaveAttribute('data-face-working', 'true');
  const bob = face.locator('[data-bob]');
  await expect(bob).toHaveCSS('animation-name', 'soft-face-work-body');
  const transform = () => bob.evaluate(el => getComputedStyle(el).transform);
  const first = await transform();
  await expect.poll(transform).not.toBe(first);
  await page.waitForTimeout(2000);
  const later = await transform(); await expect.poll(transform).not.toBe(later);
  await page.reload();
  await expect(face).toHaveAttribute('data-face-working', 'true');
  await page.getByRole('button', { name: '打开群聊 Soft motion', exact: true }).click();
  const groupFace = page.getByTestId(`room-working-face-${a.id}`);
  await expect(groupFace).toHaveAttribute('data-soft-bot-face', 'pebble');
  await expect(groupFace.locator('[data-bob]')).toHaveCSS('animation-name', 'soft-face-work-body');
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(bob).toHaveCSS('animation-name', 'none');
  await expect(groupFace.locator('.bot-face__work-label')).toBeVisible();
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await expect(bob).toHaveCSS('animation-name', 'soft-face-work-body');
  await row.scrollIntoViewIfNeeded();
  await expect(bob).toHaveCSS('animation-play-state', 'running');
  // Simulate the Page Visibility event without relying on headless tab focus semantics.
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: true }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(bob).toHaveCSS('animation-play-state', 'paused');
  await page.evaluate(() => { Object.defineProperty(document, 'hidden', { configurable: true, value: false }); document.dispatchEvent(new Event('visibilitychange')); });
  await expect(bob).toHaveCSS('animation-play-state', 'running');
  await face.evaluate(el => { el.style.transform = 'translateY(-10000px)'; });
  await expect(bob).toHaveCSS('animation-play-state', 'paused');
  await face.evaluate(el => { el.style.transform = ''; });
  await expect(bob).toHaveCSS('animation-play-state', 'running');
  active = 0;
  await expect(face).toHaveAttribute('data-face-working', 'false');
  await expect(bob).toHaveCSS('animation-name', 'bot-face-idle-body');
  await expect(groupFace).toHaveCount(0);
});
