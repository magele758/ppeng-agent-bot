import { test, expect } from '@playwright/test';

test('Bloub creation, edit, animation and reduced motion [AC:bot-bloub-dynamic#AC-1] [AC:bot-bloub-dynamic#AC-2] [AC:bot-bloub-dynamic#AC-3]', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#/agents/bots');
  await page.getByTestId('bot-create-open').click();
  const form = page.getByRole('form', { name: '新建 Bot', exact: true });
  const name = `Bloub test ${Date.now()}`;
  await form.getByTestId('bot-create-name').fill(name);
  await form.locator('summary').click();
  await form.getByTestId('bot-face-style-bloub').click();
  const preview = form.getByTestId('bot-face-choice-preview');
  await expect(preview).toHaveAttribute('data-bloub-ready', 'true');
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'dark'));
  await page.screenshot({ path: 'test-results/bloub-picker-dark.png' });
  await page.evaluate(() => document.documentElement.setAttribute('data-theme', 'light'));
  const silhouette = await preview.getAttribute('data-bloub-face');
  const color = await preview.getAttribute('data-bloub-color');
  const created = page.waitForResponse(r => r.request().method() === 'POST' && new URL(r.url()).pathname === '/api/bots');
  await form.getByTestId('bot-create-submit').click();
  const response = await created; expect(response.status(), await response.text()).toBe(201);
  const { bot } = await response.json(); expect(bot.faceStyle).toBe('bloub');
  await page.reload();
  const card = page.getByTestId(`bot-card-${bot.id}`);
  await expect(card.locator('[data-bloub-face]')).toHaveAttribute('data-bloub-face', silhouette!);
  await expect(card.locator('[data-bloub-face]')).toHaveAttribute('data-bloub-color', color!);
  await card.click();
  const detail = page.getByTestId('bot-detail');
  await detail.locator('summary').filter({ hasText: '外观' }).click();
  await detail.getByRole('button', { name: '薄荷', exact: true }).click();
  await expect.poll(async () => (await (await request.get(`/api/bots/${bot.id}`)).json()).bot.faceColor).toBe('mint');
  await page.reload();
  await page.getByTestId(`bot-card-${bot.id}`).click();
  await detail.locator('summary').filter({ hasText: '外观' }).click();
  await expect(detail.getByTestId('bot-face-style-bloub')).toHaveAttribute('aria-pressed', 'true');
  let active = 1;
  await page.route('**/api/bot-work/status', r => r.fulfill({ json: { bots: [{ bot, activeWorkCount: active }] } }));
  await detail.getByRole('button', { name: '打开对话', exact: true }).click();
  const row = page.locator('#sessionListMini .list-item--bot-chat').filter({ has: page.getByText(name, { exact: true }) });
  await row.scrollIntoViewIfNeeded();
  const face = row.locator('[data-bloub-face]');
  await page.mouse.move(0, 0);
  await expect(face).toHaveAttribute('data-face-working', 'true');
  await expect(face).toHaveAttribute('data-bloub-animated', 'true');
  const orbit = face.locator('[data-bloub-orbit]');
  const before = await orbit.getAttribute('transform');
  await expect.poll(() => orbit.getAttribute('transform')).not.toBe(before);
  await expect(face).toHaveAttribute('data-bloub-face', silhouette!);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await expect(face).toHaveAttribute('data-bloub-animated', 'false');
  const still = await orbit.getAttribute('transform');
  await page.waitForTimeout(300);
  expect(await orbit.getAttribute('transform')).toBe(still);
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await expect(face).toHaveAttribute('data-bloub-animated', 'true');
  active = 0;
  await expect(face).toHaveAttribute('data-face-working', 'false');
  await expect(face).toHaveAttribute('data-bloub-animated', 'false');
  await page.screenshot({ path: 'test-results/bloub-dynamic.png' });
  expect(errors).toEqual([]);
});
